def group_form_fields(kind, fields):
    remaining = list(fields)
    groups = []
    for title, keys in FORM_FIELD_SECTIONS.get(kind, ()):
        section_fields = [field for field in remaining if field['key'] in keys]
        if section_fields:
            groups.append({'title': title, 'fields': section_fields})
            included = {field['key'] for field in section_fields}
            remaining = [field for field in remaining if field['key'] not in included]
    if remaining:
        groups.append({'title': 'بيانات إضافية', 'fields': remaining})
    for group in groups:
        group['collapsible'] = all(not field['required'] for field in group['fields'])
    return groups


def link(kind, project_id=None, parent_id=None, entity_id=None, action=None):
    if kind == 'projects':
        base = '/pm/projects/'
    else:
        base = f'/pm/projects/{UUID(str(project_id))}/{kind}/'
    if entity_id:
        base += str(UUID(str(entity_id))) + '/'
    if action:
        base += action + '/'
    if parent_id:
        base += '?parent_id=' + str(parent_id)
    return base


